export function getCategory(slug: string) {
  return categories.find((c) => c.slug === slug);
}

export function getProduct(id: string) {
  return products.find((p) => p.id === id);
}

export function productsInCategory(slug: string) {
  return products.filter((p) => p.categories.includes(slug));
}

function normalize(s: string) {
  return s
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
}

export function searchProducts(query: string) {
  const q = normalize(query.trim());
  if (!q) return [];
  return products.filter((p) => normalize(`${p.brand} ${p.name} ${p.desc}`).includes(q));
}

export function discountPercent(p: Product) {
  if (!p.oldPrice) return 0;
  return Math.round((1 - p.price / p.oldPrice) * 100);
}

